// @vitest-environment node
import { afterEach, describe, expect, it, vi } from "vitest";
import fs from "fs";
import os from "os";
import path from "path";
import { GET } from "./route";

// /api/cockpit/board — the sidebar board lane (kanban-restructure S3):
// unfinished MWP kanban cards grouped by status, sorted status-then-
// updated, kanban/archive/** and generated views excluded. A real
// fixture vault in a tmpdir (mtimes pinned with utimesSync) so the
// parse/group/sort walk runs against the disk, not mocks.

const STATUSES_MD = `# Kanban statuses — the shared vocabulary

| Status | Meaning | Who moves it |
| --- | --- | --- |
| \`triage\` | raw idea | any agent or Brian |
| \`todo\` | real task, waiting | dispatcher |
| \`running\` | claimed, in progress | the working agent |
| \`block\` | waiting for human input | the working agent |
| \`done\` | closed | after review |
| \`cancelled\` | voided | any agent |
`;

const card = (status: string, owner = "honey") =>
  `---\ntype: task\nstatus: ${status}\nowner: ${owner}\ncreated: 2026-10-22\n---\n\n# A card\n\nBody.\n`;

function fixture(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cockpit-board-"));
  const kanban = path.join(dir, "kanban");
  fs.mkdirSync(path.join(kanban, "archive"), { recursive: true });
  fs.writeFileSync(path.join(kanban, "STATUSES.md"), STATUSES_MD);
  // unfinished cards — running x3 with distinct mtimes for the sort,
  // plus one per other unfinished vocabulary status, one off-vocabulary
  fs.writeFileSync(path.join(kanban, "run-old.md"), card("running"));
  fs.writeFileSync(path.join(kanban, "run-new.md"), card("running"));
  fs.writeFileSync(path.join(kanban, "run-mid.md"), card("running"));
  fs.writeFileSync(path.join(kanban, "a-triage.md"), card("triage"));
  fs.writeFileSync(path.join(kanban, "b-todo.md"), card("todo", "opencode"));
  fs.writeFileSync(path.join(kanban, "c-doing.md"), card("doing"));
  // finished on the top level — still excluded (not current board)
  fs.writeFileSync(path.join(kanban, "d-done.md"), card("done"));
  // archive — excluded no matter its status
  fs.writeFileSync(path.join(kanban, "archive", "e-running.md"), card("running"));
  fs.writeFileSync(path.join(kanban, "archive", "f-done.md"), card("done"));
  // generated view — a sentence in status:, not a card
  fs.writeFileSync(
    path.join(kanban, "HONEY_QUEUE.md"),
    "---\ntitle: Honey Queue\nstatus: living view — regenerated by the hook\n---\n\nqueue\n",
  );
  // pin mtimes: run-new newest, run-mid, run-old oldest
  const at = (file: string, daysAgo: number) => {
    const t = new Date(Date.now() - daysAgo * 864e5);
    fs.utimesSync(path.join(kanban, file), t, t);
  };
  at("run-new.md", 0);
  at("run-mid.md", 2);
  at("run-old.md", 9);
  return dir;
}

afterEach(() => {
  vi.unstubAllEnvs();
});

describe("GET /api/cockpit/board", () => {
  it("groups unfinished cards by status, vocabulary order, extras after", async () => {
    vi.stubEnv("MWP_VAULT", fixture());
    const res = await GET();
    expect(res.status).toBe(200);
    expect(res.headers.get("cache-control")).toBe("no-store");
    const body = (await res.json()) as {
      groups: { status: string; cards: { file: string; owner: string | null }[] }[];
      generated: string;
    };
    expect(body.groups.map((g) => g.status)).toEqual(["triage", "todo", "running", "doing"]);
    const running = body.groups.find((g) => g.status === "running")!;
    expect(running.cards.map((c) => c.file)).toEqual(["run-new.md", "run-mid.md", "run-old.md"]);
    expect(body.groups.find((g) => g.status === "todo")!.cards[0].owner).toBe("opencode");
  });

  it("excludes finished cards, kanban/archive/**, and generated views", async () => {
    vi.stubEnv("MWP_VAULT", fixture());
    const body = (await (await GET()).json()) as {
      groups: { cards: { file: string }[] }[];
    };
    const files = body.groups.flatMap((g) => g.cards.map((c) => c.file));
    expect(files).not.toContain("d-done.md"); // finished, top level
    expect(files).not.toContain("e-running.md"); // archive/** — status irrelevant
    expect(files).not.toContain("f-done.md"); // archive/**
    expect(files).not.toContain("HONEY_QUEUE.md"); // sentence status — a view
    expect(files).toHaveLength(6);
  });

  it("answers 503 for an unreadable vault — never a fake-clear board", async () => {
    vi.stubEnv("MWP_VAULT", "/nonexistent/vault");
    const res = await GET();
    expect(res.status).toBe(503);
    expect(res.headers.get("cache-control")).toBe("no-store");
    const body = (await res.json()) as { error: string };
    expect(body.error).toContain("not found");
  });
});
